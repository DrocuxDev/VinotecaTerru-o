import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { dedup, prune, weld, simplify } from '@gltf-transform/functions';
import { MeshoptSimplifier } from 'meshoptimizer';
import fs from 'node:fs/promises';
const source = process.argv[2];
if (!source) throw new Error('Usage: node scripts/prepare-model.mjs /path/to/source.glb');
await fs.mkdir('public/models', { recursive: true });
await fs.mkdir('docs', { recursive: true });
await MeshoptSimplifier.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const document = await io.read(source);
const count = () => document.getRoot().listMeshes().flatMap(mesh => mesh.listPrimitives()).reduce((sum, primitive) => sum + (primitive.getIndices()?.getCount() ?? primitive.getAttribute('POSITION').getCount()) / 3, 0);
const before = count();
await document.transform(dedup(), weld(), simplify({ simplifier: MeshoptSimplifier, ratio: Math.min(1, 20000 / before), error: 0.002, lockBorder: true }), prune());
await io.write('public/models/terruno-bottle.glb', document);
const report = { source, inputBytes: (await fs.stat(source)).size, inputTriangles: before, outputTriangles: count(), outputBytes: (await fs.stat('public/models/terruno-bottle.glb')).size, texturePolicy: 'Original embedded textures preserved; geometry simplified with UV border lock.', visualReview: false };
await fs.writeFile('docs/model-report.json', JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
